/// Source-copy installer. No third-party runtime dependencies.
library;

import 'dart:convert';
import 'dart:io';
import 'dart:isolate';

const _groups = <String, List<String>>{
  'button': [],
  'display': [],
  'forms': ['button'],
  'navigation': ['button'],
  'overlays': ['button', 'forms'],
  'advanced': ['button'],
  'code_block': ['button'],
  'composition': [],
  'messaging': ['button'],
  'questionnaire': ['button', 'display', 'forms'],
  'charts': ['button'],
  'table': [],
};

Future<void> main(List<String> args) async {
  try {
    await _run(args);
  } on Object catch (error) {
    stderr.writeln('flappa_ui: $error');
    exitCode = 1;
  }
}

Future<void> _run(List<String> args) async {
  if (args.isEmpty || args.contains('--help')) {
    stdout.writeln('''Flappa UI — own your components

  dart run flappa_ui init [--path lib/ui]
  dart run flappa_ui add <group|all> [--path lib/ui] [--force]
  dart run flappa_ui list

Groups: ${_groups.keys.join(', ')}
Copies Dart source into your app. Existing files require --force.
Import <destination>/flappa_ui.dart. Add uses-material-design: true
under flutter: in your application's pubspec.yaml.''');
    return;
  }
  final command = args.first;
  if (command == 'list') {
    stdout.writeln(_groups.keys.join('\n'));
    return;
  }
  if (command != 'init' && command != 'add') {
    throw ArgumentError('Unknown command: $command');
  }
  var destination = 'lib/ui';
  var force = false;
  final requested = <String>[];
  for (var i = 1; i < args.length; i++) {
    if (args[i] == '--path') {
      if (++i >= args.length) {
        throw ArgumentError('--path requires a directory');
      }
      destination = args[i];
    } else if (args[i] == '--force') {
      force = true;
    } else if (args[i].startsWith('-')) {
      throw ArgumentError('Unknown option: ${args[i]}');
    } else {
      requested.add(args[i]);
    }
  }
  if (command == 'add' && requested.isEmpty) {
    throw ArgumentError('Choose a group or all');
  }
  if (command == 'init' && requested.isNotEmpty) {
    throw ArgumentError('init takes no group names');
  }
  final groups = <String>{};
  void resolve(String group) {
    if (!_groups.containsKey(group)) {
      throw ArgumentError('Unknown group: $group');
    }
    if (groups.add(group)) {
      for (final dependency in _groups[group]!) {
        resolve(dependency);
      }
    }
  }

  for (final group in requested) {
    if (group == 'all') {
      _groups.keys.forEach(resolve);
    } else {
      resolve(group);
    }
  }
  final packageUri = await Isolate.resolvePackageUri(
    Uri.parse('package:flappa_ui/flappa_ui.dart'),
  );
  if (packageUri == null) {
    throw StateError(
      'Could not locate flappa_ui. Add it to pubspec.yaml first.',
    );
  }
  final root = Directory(destination).absolute;
  final marker = File('${root.path}/.flappa.json');
  final previous = marker.existsSync()
      ? (jsonDecode(await marker.readAsString()) as Map<String, dynamic>)
      : <String, dynamic>{};
  final installed = {
    ...(previous['groups'] as List<dynamic>? ?? []).cast<String>(),
    ...groups,
  };
  final sources = <String, String>{};
  // Preserve the project's existing theme unless an explicit forced init is used.
  if (!File('${root.path}/src/theme/theme.dart').existsSync() ||
      (command == 'init' && force)) {
    sources['src/theme/theme.dart'] = await File.fromUri(
      packageUri.resolve('src/theme/theme.dart'),
    ).readAsString();
  } else if (!marker.existsSync()) {
    throw StateError(
      'Destination contains an untracked theme. Choose a different --path.',
    );
  }
  for (final group in groups) {
    sources['src/components/$group.dart'] = await File.fromUri(
      packageUri.resolve('src/components/$group.dart'),
    ).readAsString();
  }
  final sorted = installed.toList()..sort();
  final barrel =
      "// Generated by flappa_ui. Customize component source files freely.\nexport 'src/theme/theme.dart';\n${sorted.map((g) => "export 'src/components/$g.dart';").join('\n')}\n";
  final barrelFile = File('${root.path}/flappa_ui.dart');
  if (barrelFile.existsSync() && !marker.existsSync() && !force) {
    throw StateError(
      'flappa_ui.dart already exists. Choose another --path or use --force.',
    );
  }
  if (barrelFile.existsSync() && marker.existsSync() && !force) {
    final priorGroups =
        (previous['groups'] as List<dynamic>? ?? []).cast<String>().toList()
          ..sort();
    final expected =
        "// Generated by flappa_ui. Customize component source files freely.\nexport 'src/theme/theme.dart';\n${priorGroups.map((g) => "export 'src/components/$g.dart';").join('\n')}\n";
    if (await barrelFile.readAsString() != expected) {
      throw StateError(
        'flappa_ui.dart has local changes. Use --force to replace it.',
      );
    }
  }
  // Preflight all collisions before writing any files.
  for (final entry in sources.entries) {
    final target = File('${root.path}/${entry.key}');
    if (target.existsSync() &&
        await target.readAsString() != entry.value &&
        !force) {
      throw StateError(
        '${entry.key} has local changes. Use --force to replace it.',
      );
    }
  }
  for (final entry in sources.entries) {
    final target = File('${root.path}/${entry.key}');
    await target.parent.create(recursive: true);
    await target.writeAsString(entry.value);
  }
  await barrelFile.writeAsString(barrel);
  await marker.writeAsString(
    '${const JsonEncoder.withIndent('  ').convert({'version': 1, 'groups': sorted})}\n',
  );
  stdout.writeln(
    'Installed ${sorted.isEmpty ? 'theme' : sorted.join(', ')} in ${root.path}',
  );
  stdout.writeln('Import ${root.path}/flappa_ui.dart to get started.');
}
